#!/bin/bash
# Called by OpenVPN on connect (script_type=up) and disconnect (script_type=down).
# Mirrors the role of configs/vpnc-script for openconnect connections.
#
# Custom env vars injected by the driver via --setenv:
#   VPNNAME, VPN_INTERFACE_ID, VPN_CONFIG_FILE, DNSMASQ_DIR
#
# Standard OpenVPN env vars set by the daemon:
#   script_type        -- "up" or "down"
#   dev                -- tunnel interface name, e.g. tun43
#   ifconfig_local     -- IP assigned to this client
#   ifconfig_remote    -- peer IP (point-to-point tun mode)
#   route_vpn_gateway  -- VPN gateway
#   route_network_N    -- pushed route network (N=1,2,...)
#   route_netmask_N    -- pushed route netmask
#   route_gateway_N    -- pushed route gateway
#   foreign_option_N   -- pushed dhcp-options (DNS, DOMAIN, etc.)

PATH=/sbin:/usr/sbin:$PATH
IPROUTE=$(which ip 2>/dev/null)
DNSMASQ_DIR=${DNSMASQ_DIR:-/data/dnsmasq.d}

# Convert a dotted-quad netmask to a CIDR prefix length.
mask2cidr() {
  local mask=$1 cidr=0
  local IFS=.
  for octet in $mask; do
    case $octet in
      255) cidr=$((cidr+8)) ;;
      254) cidr=$((cidr+7)) ;;
      252) cidr=$((cidr+6)) ;;
      248) cidr=$((cidr+5)) ;;
      240) cidr=$((cidr+4)) ;;
      224) cidr=$((cidr+3)) ;;
      192) cidr=$((cidr+2)) ;;
      128) cidr=$((cidr+1)) ;;
    esac
  done
  echo $cidr
}

do_up() {
  # ── Pushed routes → VPN routing table ─────────────────────────────────────
  # OpenVPN sets route_network_1, route_netmask_1, route_gateway_1, etc.
  # We add each to the VPN-specific routing table AND install an ip rule so
  # unmarked traffic can reach these destinations without needing DNS first.
  local n=1
  while true; do
    local net mask gw
    # bash indirect variable reference
    net=$(eval echo "\${route_network_${n}:-}")
    mask=$(eval echo "\${route_netmask_${n}:-}")
    gw=$(eval echo "\${route_gateway_${n}:-}")
    [ -z "$net" ] && break

    local cidr
    cidr=$(mask2cidr "$mask")
    if [ -n "$cidr" ] && [ "$net" != "0.0.0.0" ]; then
      if [ -n "$gw" ] && [ "$gw" != "0.0.0.0" ]; then
        $IPROUTE route replace "$net/$cidr" via "$gw" dev "$dev" \
          table "$VPN_INTERFACE_ID" 2>/dev/null || true
      else
        $IPROUTE route replace "$net/$cidr" dev "$dev" \
          table "$VPN_INTERFACE_ID" 2>/dev/null || true
      fi
      $IPROUTE rule add to "$net/$cidr" lookup "$VPN_INTERFACE_ID" 2>/dev/null || true
      echo "openvpn_updown[$VPNNAME]: route $net/$cidr -> table $VPN_INTERFACE_ID"
    fi
    n=$((n+1))
  done

  # ── DNS from pushed dhcp-options ──────────────────────────────────────────
  local dns_servers="" pushed_domains=""
  local i=1
  while true; do
    local opt
    opt=$(eval echo "\${foreign_option_${i}:-}")
    [ -z "$opt" ] && break
    case "$opt" in
      "dhcp-option DNS "*)
        dns_servers="$dns_servers $(echo "$opt" | awk '{print $3}')" ;;
      "dhcp-option DOMAIN "*)
        pushed_domains="$pushed_domains $(echo "$opt" | awk '{print $3}')" ;;
    esac
    i=$((i+1))
  done

  # Merge pushed domains with additional_domains from JSON config
  local json_domains=""
  [ -f "$VPN_CONFIG_FILE" ] && \
    json_domains=$(jq -r '.additional_domains // [] | .[]' "$VPN_CONFIG_FILE" 2>/dev/null | tr '\n' ' ')

  # Deduplicate and collect final domain list
  local all_domains
  all_domains=$(printf '%s\n' $pushed_domains $json_domains | grep -v '^$' | sort -u)

  dns_servers=$(echo "$dns_servers" | tr ' ' '\n' | grep -v '^$' | sort -u | tr '\n' ' ' | xargs)

  if [ -n "$dns_servers" ] && [ -n "$all_domains" ]; then
    local first_dns
    first_dns=$(echo "$dns_servers" | awk '{print $1}')

    # Route every DNS server through the VPN
    for dns in $dns_servers; do
      $IPROUTE route replace "${dns}/32" dev "$dev" table "$VPN_INTERFACE_ID" 2>/dev/null || true
      $IPROUTE rule add to "${dns}/32" lookup "$VPN_INTERFACE_ID" 2>/dev/null || true
    done

    # dnsmasq config: per-domain upstream + nftset for auto-routing resolved IPs
    local conf_file="${DNSMASQ_DIR}/vpn${VPN_INTERFACE_ID}-${VPNNAME}.conf"
    {
      echo "# Generated by openvpn_updown.sh for $VPNNAME"
      while read -r domain; do
        [ -n "$domain" ] || continue
        echo "server=/${domain}/${first_dns}"
        echo "nftset=/${domain}/4#ip#routehouse_${VPN_INTERFACE_ID}#auto_routes"
      done <<< "$all_domains"
    } > "$conf_file"

    # nftables table for auto-routing DNS-resolved IPs (same pattern as vpnc-script)
    nft "add table ip routehouse_${VPN_INTERFACE_ID}" 2>/dev/null || true
    nft "add set ip routehouse_${VPN_INTERFACE_ID} auto_routes { type ipv4_addr ; flags dynamic ; }" 2>/dev/null || true
    nft "add chain ip routehouse_${VPN_INTERFACE_ID} out { type route hook output priority mangle ; }" 2>/dev/null || true
    nft "add rule ip routehouse_${VPN_INTERFACE_ID} out ip daddr @auto_routes meta mark set ${VPN_INTERFACE_ID}" 2>/dev/null || true
    nft "add chain ip routehouse_${VPN_INTERFACE_ID} pre { type filter hook prerouting priority mangle ; }" 2>/dev/null || true
    nft "add rule ip routehouse_${VPN_INTERFACE_ID} pre ip daddr @auto_routes meta mark set ${VPN_INTERFACE_ID}" 2>/dev/null || true

    $IPROUTE rule add fwmark "$VPN_INTERFACE_ID" lookup "$VPN_INTERFACE_ID" priority 200 2>/dev/null || true
    $IPROUTE route flush cache 2>/dev/null || true

    supervisorctl restart dnsmasq 2>/dev/null || pkill -TERM -x dnsmasq 2>/dev/null || true
    pkill -HUP -x squid   2>/dev/null || true
    echo "openvpn_updown[$VPNNAME]: DNS configured for $(echo "$all_domains" | tr '\n' ' ') via $first_dns"
  fi
}

do_down() {
  rm -f "${DNSMASQ_DIR}/vpn${VPN_INTERFACE_ID}-"*.conf 2>/dev/null || true
  nft delete table ip "routehouse_${VPN_INTERFACE_ID}" 2>/dev/null || true
  $IPROUTE rule del fwmark "$VPN_INTERFACE_ID" lookup "$VPN_INTERFACE_ID" 2>/dev/null || true
  $IPROUTE route flush cache 2>/dev/null || true
  supervisorctl restart dnsmasq 2>/dev/null || pkill -TERM -x dnsmasq 2>/dev/null || true
  pkill -HUP -x squid   2>/dev/null || true
  echo "openvpn_updown[$VPNNAME]: teardown complete"
}

case "${script_type:-}" in
  up)   do_up   ;;
  down) do_down ;;
  *)
    echo "openvpn_updown: unknown script_type '${script_type:-}'" >&2
    exit 1
    ;;
esac

exit 0
