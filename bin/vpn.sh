#!/bin/bash

SCRIPT_DIR=$( cd -- "$( dirname -- "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )
# Absolute paths — must match the container layout and what vpnc-script hardcodes.
CONFIG_DIR=/data/vpns
DNSMASQ_DIR=/data/dnsmasq.d

. $SCRIPT_DIR/funcs.sh

# =========== helpers ==========================================================

usage() {
  echo "Usage: vpn.sh <command> [vpn-name]"
  echo ""
  echo "Commands:"
  echo "  start <name>   Start the given VPN"
  echo "  stop  <name>   Stop the given VPN"
  echo "  status [name]  Show status of all (or one) configured VPN(s)"
  exit 1
}

require_vpn_name() {
  local cmd=$1 name=$2
  if [ -z "$name" ]; then
    echo "Error: '$cmd' requires a VPN name."
    usage
  fi
  if [ ! -e "${CONFIG_DIR}/${name}.json" ]; then
    echo "Error: Config file '${CONFIG_DIR}/${name}.json' not found."
    exit 1
  fi
}

# Returns the interface name for a given VPN type and interface_id.
# New driver types: add a case here and set DRIVER_IF_PREFIX in the driver file.
get_if_name() {
  local type=$1 id=$2
  case "$type" in
    ipsec) echo "xfrm${id}" ;;
    *)     echo "tun${id}"  ;;
  esac
}

# Sources the driver file for the given type and validates it provides the
# required contract (DRIVER_IF_PREFIX, driver_connect, driver_disconnect).
load_driver() {
  local type=$1
  local driver_file="$SCRIPT_DIR/vpn_driver_${type}.sh"
  if [ ! -f "$driver_file" ]; then
    echo "Error: no driver found for VPN type '$type' (expected $driver_file)" >&2
    exit 1
  fi
  . "$driver_file"
}

# =========== start ============================================================

cmd_start() {
  export VPNNAME=$1
  require_vpn_name "start" "$VPNNAME"

  export VPN_CONFIG_FILE="${CONFIG_DIR}/${VPNNAME}.json"
  eval "$(parse_json "$VPN_CONFIG_FILE" vpn_)"

  # Capture all subsequent output in the log file.  web.py discards our
  # stdout/stderr, so without this nothing from cmd_start ever reaches the log.
  exec >> "$vpn_log_file" 2>&1
  echo "[$(date '+%Y-%m-%d %H:%M:%S')] === cmd_start: $VPNNAME ==="

  local vpn_type
  vpn_type=$(get_vpn_type "$VPN_CONFIG_FILE")

  load_driver "$vpn_type"

  export VPN_IF="${DRIVER_IF_PREFIX}${vpn_interface_id}"

  vpn_debug=${vpn_debug:="false"}

  # Check if VPN is already running
  if [ -f "$vpn_pid_file" ]; then
    EXISTING_PID=$(cat "$vpn_pid_file" 2>/dev/null)
    if [ -n "$EXISTING_PID" ] && kill -0 "$EXISTING_PID" 2>/dev/null; then
      echo "Error: VPN '$VPNNAME' is already running (PID: $EXISTING_PID)"
      echo "If you want to restart it, stop it first or kill the process."
      exit 1
    fi
    rm -f "$vpn_pid_file"
  fi

  driver_connect
  CONNECT_RES=$?

  # Wait for the interface to come up (max 15 seconds)
  IFUPRES=1
  for i in {1..15}; do
    ip link show "$VPN_IF" up >/dev/null 2>&1
    IFUPRES=$?
    [ $IFUPRES -eq 0 ] && break
    sleep 1
  done

  if [ $CONNECT_RES -eq 0 ] && [ $IFUPRES -eq 0 ]; then
    echo "Success!"

    # NAT traffic leaving via the tunnel (needed for LAN clients / proxies)
    echo "Enabling MASQUERADE on $VPN_IF"
    vpn_masq_add "$VPN_IF"

    echo "Adding routes:"
    echo "$vpn_manual_routes" | while read -r route; do
      if [ -n "$route" ]; then
        echo "  Route: $route -> table $vpn_interface_id"
        sudo ip rule add to "$route" lookup "$vpn_interface_id"
      fi
    done

    # Export routes via BIRD RIPv2 if configured
    local bird_conf="/data/bird/vpn-${VPNNAME}.conf"
    if [ -n "$vpn_exported_routes" ]; then
      mkdir -p /data/bird
      local proto_name
      proto_name="vpn_$(echo "$VPNNAME" | tr '-' '_')"
      {
        echo "# Generated by vpn.sh for VPN: ${VPNNAME}"
        echo "protocol static ${proto_name} {"
        echo "    ipv4;"
        echo "$vpn_exported_routes" | while read -r route; do
          [ -n "$route" ] && echo "    route $route blackhole;"
        done
        echo "}"
      } > "$bird_conf"
      birdc -s /var/run/bird/bird.ctl configure 2>/dev/null || true
      echo "Exported routes via BIRD RIPv2: $(echo "$vpn_exported_routes" | tr '\n' ' ')"
    fi

    echo "Running up commands:"
    echo "$vpn_up_cmds" | while read -r cmd; do
      if [ -n "$cmd" ]; then
        echo "  up_cmd: $cmd"
        eval "$cmd"
        rc=$?
        if [ $rc -ne 0 ]; then
          echo "  up_cmd FAILED (exit $rc): $cmd"
        else
          echo "  up_cmd OK"
        fi
      fi
    done

    # Restart dnsmasq so it picks up any conf files written during connect.
    # SIGHUP only re-reads /etc/hosts; a full restart is needed for conf-dir.
    echo "Restarting dnsmasq to pick up new config..."
    supervisorctl restart dnsmasq 2>&1 || true

    # Start keepalive processes if configured
    local keepalive_count
    keepalive_count=$(jq -r '.keepalive | length // 0' "$VPN_CONFIG_FILE" 2>/dev/null)
    if [ "$keepalive_count" -gt 0 ]; then
      echo "Starting keepalive processes:"
      for i in $(seq 0 $((keepalive_count - 1))); do
        local ka_type ka_target ka_interval
        ka_type=$(jq -r ".keepalive[$i].type" "$VPN_CONFIG_FILE")
        ka_target=$(jq -r ".keepalive[$i].target" "$VPN_CONFIG_FILE")
        ka_interval=$(jq -r ".keepalive[$i].interval" "$VPN_CONFIG_FILE")
        if [ -n "$ka_type" ] && [ "$ka_type" != "null" ] && \
           [ -n "$ka_target" ] && [ "$ka_target" != "null" ] && \
           [ -n "$ka_interval" ] && [ "$ka_interval" != "null" ]; then
          echo "  $ka_type $ka_target every ${ka_interval}s"
          nohup $SCRIPT_DIR/keepalive.sh \
            "$ka_type" "$ka_target" "$ka_interval" \
            "$VPNNAME" "$vpn_debug" "$vpn_pid_file" > /dev/null 2>&1 &
        fi
      done
    fi

    # Start watchdog — handles cleanup when the VPN process dies for any reason
    nohup $SCRIPT_DIR/vpn_watchdog.sh \
        "$vpn_interface_id" "$vpn_pid_file" \
        "$DNSMASQ_DIR" "$VPN_CONFIG_FILE" \
        >> "$vpn_log_file" 2>&1 &
  else
    echo "Failed."
    exit 1
  fi
}

# =========== stop =============================================================

cleanup_vpn_dnsmasq() {
  local id=$1
  for f in ${DNSMASQ_DIR}/vpn${id}-*.conf; do
    if [ -f "$f" ]; then
      rm -f "$f"
      echo "Removed dnsmasq config: $f"
    fi
  done
  supervisorctl restart dnsmasq 2>/dev/null || pkill -TERM -x dnsmasq 2>/dev/null || true
  pkill -HUP -x squid   2>/dev/null || true
}

cmd_stop() {
  local VPNNAME=$1
  require_vpn_name "stop" "$VPNNAME"

  export VPN_CONFIG_FILE="${CONFIG_DIR}/${VPNNAME}.json"
  eval "$(parse_json "$VPN_CONFIG_FILE" vpn_)"

  local vpn_type
  vpn_type=$(get_vpn_type "$VPN_CONFIG_FILE")

  load_driver "$vpn_type"

  export VPN_IF="${DRIVER_IF_PREFIX}${vpn_interface_id}"

  if [ ! -f "$vpn_pid_file" ]; then
    echo "VPN '$VPNNAME' is not running (no PID file)."
    cleanup_vpn_dnsmasq "$vpn_interface_id"
    exit 1
  fi

  PID=$(cat "$vpn_pid_file" 2>/dev/null)
  if [ -z "$PID" ] || ! kill -0 "$PID" 2>/dev/null; then
    echo "VPN '$VPNNAME' is not running (stale PID file)."
    rm -f "$vpn_pid_file"
    cleanup_vpn_dnsmasq "$vpn_interface_id"
    exit 1
  fi

  echo "Stopping VPN '$VPNNAME' (PID: $PID)..."

  # Type-specific teardown before killing the main process
  # (e.g. terminate IPsec SA; no-op for openconnect which uses vpnc-script)
  driver_disconnect

  sudo kill "$PID"

  # Wait for process to exit (max 10 seconds)
  for i in {1..10}; do
    kill -0 "$PID" 2>/dev/null || break
    sleep 1
  done

  if kill -0 "$PID" 2>/dev/null; then
    echo "Warning: process did not exit cleanly, sending SIGKILL..."
    sudo kill -9 "$PID"
  fi

  # Run down_cmds if defined
  if [ -n "$vpn_down_cmds" ]; then
    echo "Running down commands:"
    echo "$vpn_down_cmds" | while read -r cmd; do
      if [ -n "$cmd" ]; then
        echo "  $cmd"
        $cmd
      fi
    done
  fi

  # Remove the MASQUERADE rule added by cmd_start
  echo "Removing MASQUERADE on $VPN_IF"
  vpn_masq_del "$VPN_IF"

  # Remove policy routing rules added by cmd_start and/or the updown script
  echo "Removing IP routing rules for table $vpn_interface_id..."
  while sudo ip rule del table "$vpn_interface_id" 2>/dev/null; do :; done

  # Remove BIRD exported routes config and reload
  local bird_conf="/data/bird/vpn-${VPNNAME}.conf"
  if [ -f "$bird_conf" ]; then
    rm -f "$bird_conf"
    birdc -s /var/run/bird/bird.ctl configure 2>/dev/null || true
    echo "Removed BIRD exported routes for $VPNNAME"
  fi

  cleanup_vpn_dnsmasq "$vpn_interface_id"

  # Remove PID file last — watchdog uses its absence as "clean stop" signal
  rm -f "$vpn_pid_file"

  echo "VPN '$VPNNAME' stopped."
}

# =========== status ===========================================================

cmd_status() {
  local filter=$1
  local found=0

  for json in $(ls ${CONFIG_DIR}/*.json 2>/dev/null | sort); do
    [ -f "$json" ] || continue
    local name
    name=$(basename "$json" .json)

    if [ -n "$filter" ] && [ "$name" != "$filter" ]; then
      continue
    fi

    found=1

    (
      eval "$(parse_json "$json" vpn_)"
      local vpn_type if_name
      vpn_type=$(get_vpn_type "$json")
      if_name=$(get_if_name "$vpn_type" "$vpn_interface_id")

      if [ -f "$vpn_pid_file" ]; then
        PID=$(cat "$vpn_pid_file" 2>/dev/null)
        if [ -n "$PID" ] && kill -0 "$PID" 2>/dev/null; then
          printf "  %-20s running   (PID %s, %s)\n" "$name" "$PID" "$if_name"
        else
          printf "  %-20s stopped   (stale PID file)\n" "$name"
        fi
      else
        printf "  %-20s stopped\n" "$name"
      fi
    )
  done

  if [ $found -eq 0 ]; then
    if [ -n "$filter" ]; then
      echo "No VPN config found for '$filter'."
    else
      echo "No VPN configs found in ${CONFIG_DIR}."
    fi
  fi
}

# =========== dispatch =========================================================

COMMAND=$1

case "$COMMAND" in
  start)
    cmd_start "$2"
    ;;
  stop)
    cmd_stop "$2"
    ;;
  status)
    cmd_status "$2"
    ;;
  *)
    usage
    ;;
esac
