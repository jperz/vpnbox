#!/bin/bash
# Called by strongSwan (charon) when an IPsec child SA comes up or goes down.
# Mirrors the role of configs/vpnc-script for openconnect connections.
#
# Required env vars set by the per-VPN updown wrapper (/tmp/vpnbox_updown_<name>.sh):
#   VPNNAME           -- VPN name (matches the swanctl connection name)
#   VPN_IF            -- XFRM interface name, e.g. xfrm50
#   VPN_INTERFACE_ID  -- numeric ID, used as routing table number
#   VPN_CONFIG_FILE   -- path to the VPN JSON config
#   DNSMASQ_DIR       -- directory for per-VPN dnsmasq config files
#
# Standard strongSwan PLUTO_* vars set by charon:
#   PLUTO_VERB          -- up-client, down-client, up-host, down-host
#   PLUTO_MY_SOURCEIP   -- virtual IP assigned to this client (roadwarrior)
#   PLUTO_PEER_CLIENT   -- remote subnet CIDR
#   PLUTO_DNS1/DNS2     -- DNS servers pushed by the gateway

PATH=/sbin:/usr/sbin:$PATH

DNSMASQ_DIR=${DNSMASQ_DIR:-/data/dnsmasq.d}
IPROUTE=$(which ip 2>/dev/null)

do_connect() {
  # ── Virtual IP ────────────────────────────────────────────────────────────
  if [ -n "${PLUTO_MY_SOURCEIP:-}" ]; then
    $IPROUTE addr replace "${PLUTO_MY_SOURCEIP}/32" dev "$VPN_IF" 2>/dev/null \
      || $IPROUTE addr add "${PLUTO_MY_SOURCEIP}/32" dev "$VPN_IF"
    echo "ipsec_updown[$VPNNAME]: assigned $PLUTO_MY_SOURCEIP to $VPN_IF"
  fi

  # ── Routes for remote subnet ──────────────────────────────────────────────
  # charon invokes this script once per negotiated remote traffic selector, so
  # PLUTO_PEER_CLIENT holds a single subnet per call. Three sources feed it:
  #   - site-to-site: the subnets from ipsec.remote_subnets
  #   - Cisco Unity split-include: subnets the gateway PUSHES at connect time
  #     (charon's unity plugin narrows our 0.0.0.0/0 request to this list)
  #   - full-tunnel: a lone 0.0.0.0/0 when the gateway restricts nothing
  #
  # We only POPULATE this VPN's routing table here -- listing what the tunnel can
  # reach. We deliberately do NOT add the `ip rule`s that direct host traffic at
  # the table; that is vpn.sh's job from manual_routes, so the operator chooses
  # which reachable subnets actually get policy-routed (and re-exported via BIRD)
  # rather than every peer-pushed subnet being force-activated. Peer-pushed
  # routes thus show up in `ip route show table N` but stay dormant until matched
  # by a manual_routes rule.
  if [ -n "${PLUTO_PEER_CLIENT:-}" ]; then
    if [ "$PLUTO_PEER_CLIENT" = "0.0.0.0/0" ]; then
      $IPROUTE route replace default dev "$VPN_IF" \
        table "$VPN_INTERFACE_ID" 2>/dev/null || true
      echo "ipsec_updown[$VPNNAME]: default route -> table $VPN_INTERFACE_ID"
    else
      $IPROUTE route replace "$PLUTO_PEER_CLIENT" dev "$VPN_IF" \
        table "$VPN_INTERFACE_ID" 2>/dev/null || true
      echo "ipsec_updown[$VPNNAME]: route $PLUTO_PEER_CLIENT -> table $VPN_INTERFACE_ID"
    fi
  fi

  # ── DNS setup ─────────────────────────────────────────────────────────────
  # Prefer DNS pushed by gateway; fall back to dns_server field in JSON config.
  local dns_ip="${PLUTO_DNS1:-}"
  if [ -z "$dns_ip" ] && [ -f "$VPN_CONFIG_FILE" ]; then
    dns_ip=$(jq -r '.ipsec.dns_server // ""' "$VPN_CONFIG_FILE" 2>/dev/null)
  fi

  local domains=""
  if [ -f "$VPN_CONFIG_FILE" ]; then
    domains=$(jq -r '.additional_domains // [] | .[]' "$VPN_CONFIG_FILE" 2>/dev/null)
  fi
  # Also include domain pushed by gateway if present
  if [ -n "${PLUTO_DOMAIN:-}" ]; then
    domains=$(printf '%s\n%s' "$PLUTO_DOMAIN" "$domains" | sort -u)
  fi

  if [ -n "$dns_ip" ] && [ -n "$domains" ]; then
    # Route DNS server through the VPN
    $IPROUTE route replace "${dns_ip}/32" dev "$VPN_IF" \
      table "$VPN_INTERFACE_ID" 2>/dev/null || true
    $IPROUTE rule add to "${dns_ip}/32" lookup "$VPN_INTERFACE_ID" 2>/dev/null || true

    # dnsmasq config: per-domain upstream + nftset for auto-routing resolved IPs
    local conf_file="${DNSMASQ_DIR}/vpn${VPN_INTERFACE_ID}-${VPNNAME}.conf"
    {
      echo "# Generated by ipsec_updown.sh for $VPNNAME"
      while read -r domain; do
        [ -n "$domain" ] || continue
        echo "server=/${domain}/${dns_ip}"
        echo "nftset=/${domain}/4#ip#vpnbox_${VPN_INTERFACE_ID}#auto_routes"
      done <<< "$domains"
    } > "$conf_file"

    # nftables table for auto-routing DNS-resolved IPs (same pattern as vpnc-script)
    nft "add table ip vpnbox_${VPN_INTERFACE_ID}" 2>/dev/null || true
    nft "add set ip vpnbox_${VPN_INTERFACE_ID} auto_routes { type ipv4_addr ; flags dynamic ; }" 2>/dev/null || true
    nft "add chain ip vpnbox_${VPN_INTERFACE_ID} out { type route hook output priority mangle ; }" 2>/dev/null || true
    nft "add rule ip vpnbox_${VPN_INTERFACE_ID} out ip daddr @auto_routes meta mark set ${VPN_INTERFACE_ID}" 2>/dev/null || true
    nft "add chain ip vpnbox_${VPN_INTERFACE_ID} pre { type filter hook prerouting priority mangle ; }" 2>/dev/null || true
    nft "add rule ip vpnbox_${VPN_INTERFACE_ID} pre ip daddr @auto_routes meta mark set ${VPN_INTERFACE_ID}" 2>/dev/null || true

    $IPROUTE rule add fwmark "$VPN_INTERFACE_ID" lookup "$VPN_INTERFACE_ID" priority 200 2>/dev/null || true
    $IPROUTE route flush cache 2>/dev/null || true

    pkill -HUP -x dnsmasq 2>/dev/null || true
    pkill -HUP -x squid   2>/dev/null || true
    echo "ipsec_updown[$VPNNAME]: DNS configured for $(echo "$domains" | tr '\n' ' ') via $dns_ip"
  fi
}

do_disconnect() {
  # ── Remove virtual IP ─────────────────────────────────────────────────────
  if [ -n "${PLUTO_MY_SOURCEIP:-}" ]; then
    $IPROUTE addr del "${PLUTO_MY_SOURCEIP}/32" dev "$VPN_IF" 2>/dev/null || true
  fi

  # ── Remove remote subnet route ────────────────────────────────────────────
  if [ -n "${PLUTO_PEER_CLIENT:-}" ]; then
    if [ "$PLUTO_PEER_CLIENT" = "0.0.0.0/0" ]; then
      $IPROUTE route del default dev "$VPN_IF" \
        table "$VPN_INTERFACE_ID" 2>/dev/null || true
    else
      $IPROUTE route del "$PLUTO_PEER_CLIENT" dev "$VPN_IF" \
        table "$VPN_INTERFACE_ID" 2>/dev/null || true
    fi
  fi

  # ── Remove DNS setup ──────────────────────────────────────────────────────
  local dns_ip="${PLUTO_DNS1:-}"
  if [ -z "$dns_ip" ] && [ -f "$VPN_CONFIG_FILE" ]; then
    dns_ip=$(jq -r '.ipsec.dns_server // ""' "$VPN_CONFIG_FILE" 2>/dev/null)
  fi
  if [ -n "$dns_ip" ]; then
    $IPROUTE route del "${dns_ip}/32" dev "$VPN_IF" \
      table "$VPN_INTERFACE_ID" 2>/dev/null || true
    $IPROUTE rule del to "${dns_ip}/32" lookup "$VPN_INTERFACE_ID" 2>/dev/null || true
    $IPROUTE rule del fwmark "$VPN_INTERFACE_ID" lookup "$VPN_INTERFACE_ID" 2>/dev/null || true
  fi

  nft delete table ip "vpnbox_${VPN_INTERFACE_ID}" 2>/dev/null || true
  rm -f "${DNSMASQ_DIR}/vpn${VPN_INTERFACE_ID}-"*.conf 2>/dev/null || true
  pkill -HUP -x dnsmasq 2>/dev/null || true
  pkill -HUP -x squid   2>/dev/null || true
  echo "ipsec_updown[$VPNNAME]: teardown complete"
}

case "${PLUTO_VERB:-}" in
  up-client|up-client-v6|up-host|up-host-v6)
    do_connect
    ;;
  down-client|down-client-v6|down-host|down-host-v6)
    do_disconnect
    ;;
  *)
    echo "ipsec_updown: unknown PLUTO_VERB '${PLUTO_VERB:-}'" >&2
    exit 1
    ;;
esac

exit 0
